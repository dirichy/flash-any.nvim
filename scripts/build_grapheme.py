"""Generate Unicode 17 UAX #29 pages: python scripts/build_grapheme.py INPUT_DIR."""
from pathlib import Path
import sys

source = Path(sys.argv[1])
props = bytearray(0x110000)
classes = dict(Other=0, CR=1, LF=2, Control=3, Extend=4, ZWJ=5,
               Regional_Indicator=6, Prepend=7, SpacingMark=8,
               L=9, V=10, T=11, LV=12, LVT=13)


def records(filename):
    for line in (source / filename).read_text().splitlines():
        fields = [part.strip() for part in line.split("#", 1)[0].split(";")]
        if len(fields) < 2:
            continue
        bounds = fields[0].split("..")
        yield int(bounds[0], 16), int(bounds[-1], 16), fields[1:]


for first, last, fields in records("GraphemeBreakProperty-17.0.0.txt"):
    value = classes[fields[0]]
    if value not in (12, 13):  # Hangul syllables use an arithmetic rule.
        props[first:last + 1] = bytes([value]) * (last - first + 1)
for first, last, fields in records("emoji-data-17.0.0.txt"):
    if fields[0] == "Extended_Pictographic":
        for cp in range(first, last + 1):
            props[cp] |= 16
for first, last, fields in records("DerivedCoreProperties-17.0.0.txt"):
    if fields[0] == "InCB":
        value = dict(Consonant=32, Extend=64, Linker=96)[fields[1]]
        for cp in range(first, last + 1):
            props[cp] |= value

out = ["-- Generated by scripts/build_grapheme.py; Unicode 17.0.0.",
       "-- https://www.unicode.org/Public/17.0.0/ucd/auxiliary/GraphemeBreakProperty.txt",
       "-- https://www.unicode.org/Public/17.0.0/ucd/DerivedCoreProperties.txt",
       "-- https://www.unicode.org/Public/17.0.0/ucd/emoji/emoji-data.txt",
       "-- Copyright Unicode, Inc. See licenses/Unicode-3.0.txt.",
       "-- page -> flat (low byte start, low byte end, GCB | EP<<4 | InCB<<5) ranges.",
       "return {"]
for page in range(0x1100):
    values = props[page * 256:page * 256 + 256]
    ranges = []
    start = 0
    while start < 256:
        end = start
        while end < 255 and values[end + 1] == values[start]:
            end += 1
        if values[start]:
            ranges.extend((start, end, values[start]))
        start = end + 1
    if ranges:
        out.append(f"\t[0x{page:X}] = {{ " + ", ".join(map(str, ranges)) + " },")
out.append("}")
Path("lua/flash-any/grapheme_data.lua").write_text("\n".join(out) + "\n")
